#' Generate domain-specific documentation
#' 
#' @param crosswalk The variable crosswalk dataframe
#' @param output_dir Directory to store domain documentation
#' @return TRUE if successful
generate_domain_documentation <- function(crosswalk, output_dir) {
  # Create data_sources directory if it doesn't exist
  data_sources_dir <- file.path(output_dir, "data_sources")
  if (!dir.exists(data_sources_dir)) {
    dir.create(data_sources_dir, recursive = TRUE, showWarnings = FALSE)
  }
  
  # Some key domains that need detailed documentation
  key_domains <- c(
    "Traffic Safety",
    "Health Outcomes",
    "Environmental",
    "Food Environment & Access"
  )
  
  for (domain in key_domains) {
    domain_vars <- crosswalk %>% filter(domain == domain)
    if (nrow(domain_vars) > 0) {
      # Create domain file name (replace spaces and special chars)
      file_name <- gsub(" ", "_", toupper(domain))
      file_name <- gsub("&|\\+", "AND", file_name)
      file_path <- file.path(data_sources_dir, paste0(file_name, "_DATA.md"))
      
      # Skip if the file already exists
      if (file.exists(file_path)) {
        next
      }
      
      # Create domain documentation
      content <- paste0("# ", domain, " Data\n\n")
      content <- paste0(content, "This document provides details about the ", domain, " variables in the SDOH dataset.\n\n")
      
      # Add variables table
      content <- paste0(content, "## Variables\n\n")
      content <- paste0(content, "| Variable Name | Description | Type | Years Available | Source |\n")
      content <- paste0(content, "|-------------|-------------|------|----------------|--------|\n")
      
      for (i in 1:nrow(domain_vars)) {
        var <- domain_vars[i, ]
        
        # Format years available
        years <- paste(var$min_year, "-", var$max_year)
        
        # Add row
        content <- paste0(content, 
                         "| `", var$variable_name, "` | ", 
                         var$description, " | ",
                         var$type, " | ",
                         years, " | ",
                         var$source, " |\n")
      }
      
      # Add domain-specific notes
      content <- paste0(content, "\n## Data Sources\n\n")
      
      # Add generic source information based on domain
      if (domain == "Traffic Safety") {
        content <- paste0(content, "These variables come from the National Highway Traffic Safety Administration's Fatality Analysis Reporting System (FARS), which provides data on all fatal injuries in motor vehicle traffic crashes.\n\n")
        content <- paste0(content, "- **Source Website**: https://www.nhtsa.gov/research-data/fatality-analysis-reporting-system-fars\n")
        content <- paste0(content, "- **Years Available**: 1975-present\n")
      } else if (domain == "Health Outcomes") {
        content <- paste0(content, "Health outcomes data comes from multiple sources including CDC PLACES, CDC WONDER, and the Institute for Health Metrics and Evaluation (IHME).\n\n")
        content <- paste0(content, "- **CDC PLACES**: https://www.cdc.gov/places/\n")
        content <- paste0(content, "- **CDC WONDER**: https://wonder.cdc.gov/\n")
        content <- paste0(content, "- **IHME**: http://www.healthdata.org/\n")
      }
      
      # Write to file
      writeLines(content, file_path)
      log_message(paste("Generated documentation for", domain, "variables at", file_path), 
                 level = "INFO", show_console = TRUE)
    }
  }
  
  return(TRUE)
}

